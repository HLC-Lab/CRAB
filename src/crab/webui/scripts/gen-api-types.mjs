// Regenerate src/api/generated.ts from the backend's OpenAPI schema, so the
// backend-owned response shapes (Profile, LibraryEntry, SavedEntry, ...) can't
// silently drift from their hand-used TS counterparts. Cluster-contract
// passthrough shapes (benchmarks/nodes) are NOT here — the backend forwards
// them as-is from `crab … --json`, so they stay hand-written in types.ts.
//
// Run via `npm run gen:api`. verify-full regenerates and fails on any diff.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webui = resolve(fileURLToPath(new URL("..", import.meta.url)));
const repo = resolve(webui, "../../..");
const python = join(repo, ".venv/bin/python");

const schema = execFileSync(
  python,
  [
    "-c",
    "import json; from crab.web.server import create_app; print(json.dumps(create_app().openapi()))",
  ],
  {
    cwd: repo,
    encoding: "utf8",
    env: {
      ...process.env,
      CRAB_WEB_CONFIG_DIR: mkdtempSync(join(tmpdir(), "crab-gen-")),
      CRAB_WEB_DATA_DIR: mkdtempSync(join(tmpdir(), "crab-gen-")),
    },
  },
);
const schemaFile = join(mkdtempSync(join(tmpdir(), "crab-gen-")), "openapi.json");
writeFileSync(schemaFile, schema);

const out = execFileSync("npx", ["--no-install", "openapi-typescript", schemaFile], {
  cwd: webui,
  encoding: "utf8",
});
const header =
  "// GENERATED by scripts/gen-api-types.mjs — do not edit by hand.\n// Regenerate with: npm run gen:api\n";
const target = join(webui, "src/api/generated.ts");
writeFileSync(target, header + out);
// Normalize to the project's prettier style so regeneration is byte-stable
// (verify-full diffs this file against the committed version).
execFileSync("npx", ["--no-install", "prettier", "--write", target], { cwd: webui });
console.log("wrote src/api/generated.ts");
